/* Run: node tests/overhead-comets-data.cjs

   Regression test for the Overhead comet dataset:
     data/overhead/comets.json          (generated by tools/overhead_comets_build.py)
     data/overhead/comet-ephemerides.json
     tests/fixtures/overhead/horizons-comets.json

   The test deliberately reuses no generated Python output: it re-derives what it can from the
   published numbers and the committed fixture.  In particular it
     * re-implements the two-body Kepler propagation (elliptical / parabolic / hyperbolic) and the
       JPL/Standish EM Bary position taken from the fixture itself, and checks that those reproduce
       every Horizons row in the fixture - proving the fixture is usable offline by the browser-side
       propagator;
     * recomputes the worst linear-interpolation error of every published sample grid (the browser
       interpolates linearly) instead of trusting the published number;
     * re-derives the COBS `measured` block of one comet from the raw COBS payloads in the fixture.

   No npm dependencies, no network, no Python. */
