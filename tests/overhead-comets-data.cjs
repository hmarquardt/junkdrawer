family('brightness provenance rules', () => {
  let observed = 0;
  let predictedOnly = 0;
  const magnitudes = [];
  for (const comet of comets) {
    const label = comet.id;
    const brightness = comet.brightness;
    const absolute = brightness.absolute;
    require_(Number.isFinite(absolute.M1) && Number.isFinite(absolute.K1),
      `${label}: M1/K1 are not finite`);
    assert.match(absolute.source, /M1\/K1/, `${label}.brightness.absolute.source`);
    const predicted = brightness.predicted;
    require_(Number.isFinite(predicted.magnitude), `${label}.brightness.predicted.magnitude`);
    assert.equal(predicted.model, 'M1 + 5*log10(delta) + K1*log10(r)',
      `${label}.brightness.predicted.model`);
    assert.ok(typeof predicted.caveat === 'string' && predicted.caveat.length > 20,
      `${label}.brightness.predicted needs its caveat: a prediction must be labelled`);
    const at = isoSeconds(predicted.at);
    assert.ok(at >= isoSeconds(artifact.horizon.start) - DAY_MS &&
      at <= isoSeconds(artifact.horizon.end) + DAY_MS,
      `${label}: predicted.at ${predicted.at} is outside the horizon`);
    magnitudes.push(predicted.magnitude);
    const measured = brightness.measured;
    require_(typeof measured.observed === 'boolean', `${label}.brightness.measured.observed`);
    if (measured.latest) {
      observed += 1;
      const latest = measured.latest;
      require_(Number.isFinite(latest.magnitude) && typeof latest.date === 'string',
        `${label}.measured.latest needs a magnitude and a date`);
      isoSeconds(latest.date);
      assert.ok(['visual', 'CCD', 'mixed'].includes(latest.method),
        `${label}.measured.latest.method is ${latest.method}`);
      assert.equal(latest.source, 'COBS', `${label}.measured.latest.source must be COBS`);
      assert.ok(Array.isArray(latest.methods) && latest.methods.length > 0,
        `${label}.measured.latest.methods must record which methods contributed`);
      assert.ok(latest.methods.every(m => m === 'visual' || m === 'CCD'),
        `${label}.measured.latest.methods`);
      assert.ok(Number.isInteger(latest.observer_count) && latest.observer_count >= 1,
        `${label}.measured.latest.observer_count`);
      // A measurement is in the past; the prediction is an ephemeris sample inside the horizon, so
      // a measured value carrying the prediction's timestamp would have been copied, not observed.
      assert.ok(daysBetween(artifact.horizon.start, latest.date) <= 1,
        `${label}: measured.latest.date ${latest.date} is after the horizon start`);
      assert.ok(!(latest.magnitude === predicted.magnitude && latest.date === predicted.at),
        `${label}: measured value is the prediction`);
      assert.equal(measured.observed, true, `${label}: latest present but observed is false`);
    } else {
      predictedOnly += 1;
      assert.equal(measured.observed, false, `${label}: no latest but observed is true`);
      assert.ok(typeof measured.latest_reason === 'string' && measured.latest_reason,
        `${label}: an absent observation needs a documented reason`);
    }
    const counts = measured.count;
    assert.equal(counts.total, counts.visual + counts.ccd, `${label}.measured.count.total`);
    assert.equal(measured.window_days, 120, `${label}.measured.window_days`);
    if (measured.trend === null) {
      assert.ok(typeof measured.trend_reason === 'string' && measured.trend_reason,
        `${label}: a null trend needs a documented reason`);
    } else {
      require_(Number.isFinite(measured.trend.magnitudes_per_day),
        `${label}.measured.trend.magnitudes_per_day`);
      assert.ok(measured.trend.points >= COBS_MIN_TREND_POINTS,
        `${label}.measured.trend.points below the published minimum`);
      assert.ok(measured.trend.span_days >= COBS_MIN_TREND_SPAN_DAYS,
        `${label}.measured.trend span below the published minimum`);
      assert.ok(['brightening', 'fading', 'flat'].includes(measured.trend.direction),
        `${label}.measured.trend.direction`);
    }
    if (measured.median_30d === null) {
      assert.ok(typeof measured.median_30d_reason === 'string' && measured.median_30d_reason,
        `${label}: an absent 30-day median needs a documented reason`);
    } else {
      const medianBlock = measured.median_30d;
      require_(Number.isFinite(medianBlock.magnitude), `${label}.measured.median_30d.magnitude`);
      assert.ok(medianBlock.visual_count + medianBlock.ccd_count >= 1,
        `${label}.measured.median_30d records no contributing observation`);
    }
  }
  return `${observed} comets with a COBS measurement, ${predictedOnly} with a documented absence, ` +
    `predicted magnitudes ${Math.min(...magnitudes).toFixed(1)}-${Math.max(...magnitudes).toFixed(1)}`;
});

