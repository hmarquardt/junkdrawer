function near(actual, expected, tolerance, label) {
  assert.ok(Number.isFinite(actual) && Number.isFinite(expected),
    `${label}: not finite (${actual} vs ${expected})`);
  assert.ok(Math.abs(actual - expected) <= tolerance,
    `${label}: ${actual} vs ${expected} (tolerance ${tolerance})`);
}
function isoSeconds(text) {
  require_(typeof text === 'string' && ISO_RE.test(text), `not an ISO-8601 UTC stamp: ${text}`);
  return Date.parse(text);
}
function daysBetween(a, b) {
  return (isoSeconds(b) - isoSeconds(a)) / DAY_MS;
}
function ageDays(text) {
  return (Date.now() - isoSeconds(text)) / DAY_MS;
}
function median(values) {
  const sorted = [...values].sort((a, b) => a - b);
  if (sorted.length === 0) return null;
  const middle = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
}
function sha256ish(value, label) {
  require_(typeof value === 'string' && SHA_RE.test(value), `${label}: not a SHA-256 hex digest`);
}

/* ---- two-body Kepler propagation, re-implemented from the fixture's own Earth model -------- */
function solveKepler(m, e) {
  const wrapped = m % (2 * Math.PI);
  let ecc = e < 0.8 ? wrapped : Math.PI;
  for (let i = 0; i < 100; i += 1) {
    const delta = -(ecc - e * Math.sin(ecc) - wrapped) / (1 - e * Math.cos(ecc));
    ecc += delta;
    if (Math.abs(delta) < 1e-14) break;
  }
  return ecc;
}
function solveHyperbolicKepler(m, e) {
  let h = Math.asinh(m / e);
  for (let i = 0; i < 200; i += 1) {
    const delta = -(e * Math.sinh(h) - h - m) / (e * Math.cosh(h) - 1);
    h += delta;
    if (Math.abs(delta) < 1e-14) break;
  }
  return h;
}
function solveBarker(w) {
  let d = Math.cbrt(3 * w);
  for (let i = 0; i < 200; i += 1) {
    const delta = -(d ** 3 / 3 + d - w) / (d * d + 1);
    d += delta;
    if (Math.abs(delta) < 1e-14) break;
  }
  return d;
}
function trueAnomalyAndR(e, q, tp, jd) {
  if (e < 1 - 1e-9) {
    const a = q / (1 - e);
    const ecc = solveKepler((GAUSSIAN_K / a ** 1.5) * (jd - tp), e);
    return {nu: 2 * Math.atan2(Math.sqrt(1 + e) * Math.sin(ecc / 2),
                              Math.sqrt(1 - e) * Math.cos(ecc / 2)),
            r: a * (1 - e * Math.cos(ecc))};
  }
  if (e > 1 + 1e-9) {
    const a = q / (1 - e);
    const h = solveHyperbolicKepler((GAUSSIAN_K / (-a) ** 1.5) * (jd - tp), e);
    return {nu: 2 * Math.atan2(Math.sqrt(e + 1) * Math.sinh(h / 2),
                              Math.sqrt(e - 1) * Math.cosh(h / 2)),
            r: -a * (e * Math.cosh(h) - 1)};
  }
  const d = solveBarker((3 * GAUSSIAN_K * (jd - tp)) / (2 * Math.SQRT2 * q ** 1.5));
  return {nu: 2 * Math.atan(d), r: q * (1 + d * d)};
}
function helioEcliptic(elements, jd) {
  const {nu, r} = trueAnomalyAndR(elements.e, elements.q, elements.tp, jd);
  const u = (elements.w * Math.PI) / 180 + nu;
  const node = (elements.om * Math.PI) / 180;
  const inc = (elements.i * Math.PI) / 180;
  return {
    x: r * (Math.cos(node) * Math.cos(u) - Math.sin(node) * Math.sin(u) * Math.cos(inc)),
    y: r * (Math.sin(node) * Math.cos(u) + Math.cos(node) * Math.sin(u) * Math.cos(inc)),
    z: r * Math.sin(u) * Math.sin(inc),
    r,
  };
}
function earthHelioEcliptic(jd) {
  const model = fixture.earth_model.elements;
  const t = (jd - 2451545.0) / 36525;
  const a = model.a[0] + model.a[1] * t;
  const e = model.e[0] + model.e[1] * t;
  const inc = ((model.I[0] + model.I[1] * t) * Math.PI) / 180;
  const meanLon = model.L[0] + model.L[1] * t;
  const peri = model.peri[0] + model.peri[1] * t;
  const nodeDeg = model.node[0] + model.node[1] * t;
  const w = ((peri - nodeDeg) * Math.PI) / 180;
  const node = (nodeDeg * Math.PI) / 180;
  const m = (((((meanLon - peri + 180) % 360) + 360) % 360) - 180) * (Math.PI / 180);
  const ecc = solveKepler(m, e);
  const xp = a * (Math.cos(ecc) - e);
  const yp = a * Math.sqrt(1 - e * e) * Math.sin(ecc);
  const cw = Math.cos(w), sw = Math.sin(w), cn = Math.cos(node), sn = Math.sin(node);
  const ci = Math.cos(inc), si = Math.sin(inc);
  return {
    x: (cw * cn - sw * sn * ci) * xp + (-sw * cn - cw * sn * ci) * yp,
    y: (cw * sn + sw * cn * ci) * xp + (-sw * sn + cw * cn * ci) * yp,
    z: sw * si * xp + cw * si * yp,
  };
}
function geocentric(elements, jd) {
  const comet = helioEcliptic(elements, jd);
  const earth = earthHelioEcliptic(jd);
  const dx = comet.x - earth.x, dy = comet.y - earth.y, dz = comet.z - earth.z;
  const delta = Math.sqrt(dx * dx + dy * dy + dz * dz);
  const eps = (OBLIQUITY_J2000_DEG * Math.PI) / 180;
  const xe = dx, ye = dy * Math.cos(eps) - dz * Math.sin(eps);
  const ze = dy * Math.sin(eps) + dz * Math.cos(eps);
  return {ra_deg: ((Math.atan2(ye, xe) * 180) / Math.PI + 360) % 360,
          dec_deg: (Math.atan2(ze, Math.hypot(xe, ye)) * 180) / Math.PI,
          r_au: comet.r, delta_au: delta};
}
function separationArcmin(raA, decA, raB, decB) {
  const dra = ((((raA - raB + 180) % 360) + 360) % 360) - 180;
  return Math.hypot(dra * Math.cos((decB * Math.PI) / 180), decA - decB) * 60;
}
function unwrapRa(ras) {
  const out = [ras[0]];
  for (let i = 1; i < ras.length; i += 1) {
    const previous = out[out.length - 1];
    out.push(previous + ((((ras[i] - previous + 180) % 360) + 360) % 360) - 180);
  }
  return out;
}
function midwayDeviationDeg(points) {
  if (points.length < 3) return 0;
  const ras = unwrapRa(points.map(point => point[1]));
  const decs = points.map(point => point[2]);
  let worst = 0;
  for (let i = 1; i < points.length - 1; i += 1) {
    worst = Math.max(
      worst,
      Math.abs(ras[i] - (ras[i - 1] + ras[i + 1]) / 2) * Math.cos((decs[i] * Math.PI) / 180),
      Math.abs(decs[i] - (decs[i - 1] + decs[i + 1]) / 2));
  }
  return worst;
}

