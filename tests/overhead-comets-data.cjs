family('COBS re-derivation', () => {
  const samples = fixture.cobs_samples || [];
  require_(samples.length > 0, 'the fixture must embed at least one raw COBS payload');
  const cometId = samples[0].comet;
  const comet = comets.find(item => item.id === cometId);
  require_(comet, `the fixture COBS payload belongs to ${cometId}, which is not published`);
  const cutoff = artifact.generated_at.replace('T', ' ').slice(0, 19);
  const rows = [];
  for (const sample of samples) {
    const method = sample.obs_type === 'V' ? 'visual' : 'CCD';
    for (const row of (sample.payload.objects || [])) {
      const stamp = String(row.obs_date || '').slice(0, 19);
      const magnitude = Number(row.magnitude);
      if (!/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(stamp)) continue;
      if (!Number.isFinite(magnitude)) continue;
      if (stamp > cutoff) continue;         // observed after the artifact was generated
      const observer = row.observer || {};
      const name = [observer.first_name, observer.last_name].filter(Boolean).join(' ') ||
        observer.icq_name || '';
      const coma = row.coma_diameter === null || row.coma_diameter === undefined
        ? null : Number(row.coma_diameter);
      rows.push({stamp, magnitude, method, name, coma});
    }
  }
  require_(rows.length > 0, `the fixture payloads hold no usable observation for ${cometId}`);
  const measured = comet.brightness.measured;
  const visualCount = rows.filter(row => row.method === 'visual').length;
  const ccdCount = rows.filter(row => row.method === 'CCD').length;
  assert.equal(measured.count.visual, visualCount,
    `${cometId}: published visual count ${measured.count.visual} vs payload ${visualCount}`);
  assert.equal(measured.count.ccd, ccdCount,
    `${cometId}: published CCD count ${measured.count.ccd} vs payload ${ccdCount}`);
  assert.equal(measured.count.total, rows.length, `${cometId}: published total count`);

  const latestStamp = rows.map(row => row.stamp).sort().pop();
  const group = rows.filter(row => row.stamp === latestStamp);
  const latest = measured.latest;
  require_(latest, `${cometId}: the payload has observations but the artifact has no latest`);
  assert.equal(latestStamp, latest.date.replace('T', ' ').slice(0, 19),
    `${cometId}: published latest date vs the payload's newest observation`);
  near(latest.magnitude, median(group.map(row => row.magnitude)), 1e-9,
    `${cometId}: published latest magnitude vs the payload median at that instant`);
  assert.deepEqual(latest.methods.slice().sort(),
    [...new Set(group.map(row => row.method))].sort(),
    `${cometId}: published latest methods vs the payload`);
  assert.equal(latest.observer_count, new Set(group.map(row => row.name)).size,
    `${cometId}: published observer_count vs the payload`);
  const comas = group.map(row => row.coma).filter(value => value !== null);
  if (comas.length) {
    near(latest.coma_diameter_arcmin, median(comas), 1e-9, `${cometId}: published coma diameter`);
  }

  if (measured.median_30d) {
    const from = measured.median_30d.window_start.replace('T', ' ').slice(0, 19);
    const to = measured.median_30d.window_end.replace('T', ' ').slice(0, 19);
    near(daysBetween(measured.median_30d.window_start, measured.median_30d.window_end),
      COBS_MEDIAN_DAYS, 0.05, `${cometId}: the published 30-day window must span 30 days`);
    const recent = rows.filter(row => row.stamp >= from && row.stamp <= to);
    near(measured.median_30d.magnitude, median(recent.map(row => row.magnitude)), 1e-9,
      `${cometId}: published 30-day median vs the payload`);
    assert.equal(measured.median_30d.visual_count,
      recent.filter(row => row.method === 'visual').length, `${cometId}: 30-day visual count`);
    assert.equal(measured.median_30d.ccd_count,
      recent.filter(row => row.method === 'CCD').length, `${cometId}: 30-day CCD count`);
  }

  if (measured.trend) {
    const fits = ['visual', 'CCD'].map(method => {
      const subset = rows.filter(row => row.method === method);
      if (subset.length < COBS_MIN_TREND_POINTS) return null;
      const times = subset.map(row => Date.parse(`${row.stamp.replace(' ', 'T')}Z`) / DAY_MS);
      const span = Math.max(...times) - Math.min(...times);
      if (span < COBS_MIN_TREND_SPAN_DAYS) return null;
      const meanX = times.reduce((a, b) => a + b, 0) / times.length;
      const meanY = subset.reduce((a, row) => a + row.magnitude, 0) / subset.length;
      const sxx = times.reduce((sum, time) => sum + (time - meanX) ** 2, 0);
      const sxy = times.reduce((sum, time, i) =>
        sum + (time - meanX) * (subset[i].magnitude - meanY), 0);
      return {method, points: subset.length, span_days: span, slope: sxy / sxx};
    }).filter(Boolean).sort((a, b) => b.points - a.points || a.method.localeCompare(b.method));
    require_(fits.length > 0, `${cometId}: the published trend is not reproducible from the payload`);
    near(measured.trend.magnitudes_per_day, fits[0].slope, 1e-4,
      `${cometId}: published trend slope vs the payload`);
    assert.equal(measured.trend.points, fits[0].points, `${cometId}: trend points`);
    near(measured.trend.span_days, fits[0].span_days, 0.02, `${cometId}: trend span`);
    assert.deepEqual(measured.trend.method, [fits[0].method], `${cometId}: trend method`);
  }
  return `${rows.length} observations of ${cometId} re-derived from the raw COBS payload ` +
    `(${visualCount} visual, ${ccdCount} CCD)`;
});

