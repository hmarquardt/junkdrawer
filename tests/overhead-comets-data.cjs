function interpolateSample(points, tms) {
  // The browser's lookup: linear between the two bracketing samples, RA unwrapped across 0/360.
  if (tms <= Date.parse(points[0][0])) return points[0].slice(1);
  const last = points[points.length - 1];
  if (tms >= Date.parse(last[0])) return last.slice(1);
  let index = 0;
  while (index < points.length - 1 && Date.parse(points[index + 1][0]) < tms) index += 1;
  const a = points[index], b = points[index + 1];
  const t0 = Date.parse(a[0]), t1 = Date.parse(b[0]);
  const frac = (tms - t0) / (t1 - t0);
  const dra = ((((b[1] - a[1] + 180) % 360) + 360) % 360) - 180;
  return [((a[1] + frac * dra) % 360 + 360) % 360,
          a[2] + frac * (b[2] - a[2]),
          a[3] + frac * (b[3] - a[3]),
          a[4] + frac * (b[4] - a[4])];
}

